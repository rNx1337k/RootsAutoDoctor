"""Idioma da interface: o catálogo inglês cobre todos os textos, os marcadores {…} batem certo com os valores
passados em cada tr(), e a troca de idioma muda o que o utilizador vê (módulos, avarias, relatório…).
Corre sem Qt."""
import ast
import glob
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, ROOT)
sys.path.insert(0, os.path.join(ROOT, "tools"))

from rad import i18n
from rad.i18n_en import EN

PLACEHOLDER = re.compile(r"(?<!\{)\{([A-Za-z_][A-Za-z0-9_]*)[^{}]*\}(?!\})")


def _names(text):
    return sorted(PLACEHOLDER.findall(text))


def test_catalog_covers_every_text():
    import i18n_check
    missing = i18n_check.missing()
    assert not missing, f"{len(missing)} texto(s) sem tradução, ex.: {missing[:5]} — corra tools/i18n_check.py"


def test_translations_keep_placeholders_and_html():
    tag = re.compile(r"</?([a-zA-Z]+)")
    for pt, en in EN.items():
        assert _names(pt) == _names(en), (pt, en)
        assert sorted(tag.findall(pt)) == sorted(tag.findall(en)), (pt, en)
        assert en.strip(), pt


def test_every_tr_call_passes_the_values_its_text_needs():
    """tr("… {x} …") sem x=… mostraria "{x}" ao utilizador; x=… sem {x} perde o valor."""
    problems = []
    for path in glob.glob(os.path.join(ROOT, "rad", "**", "*.py"), recursive=True):
        tree = ast.parse(open(path, encoding="utf-8").read())
        for n in ast.walk(tree):
            if not (isinstance(n, ast.Call) and isinstance(n.func, ast.Name) and n.func.id == "tr"):
                continue
            if not (n.args and isinstance(n.args[0], ast.Constant) and isinstance(n.args[0].value, str)):
                problems.append(f"{os.path.relpath(path, ROOT)}:{n.lineno} tr() sem texto literal (use tr_data)")
                continue
            if any(k.arg is None for k in n.keywords):          # **kwargs: não se pode verificar
                continue
            needed = set(_names(n.args[0].value))
            given = {k.arg for k in n.keywords}
            if needed != given:
                problems.append(f"{os.path.relpath(path, ROOT)}:{n.lineno} {sorted(needed)} vs {sorted(given)}")
    assert not problems, "\n".join(problems)


def test_tr_fallback_and_formatting():
    i18n.set_language("pt")
    assert i18n.tr("Ligado a {where}", where="01") == "Ligado a 01"
    i18n.set_language("en")
    try:
        assert i18n.tr("Ligado a {where}", where="01") == "Connected to 01"
        assert i18n.tr("Texto que não existe no catálogo") == "Texto que não existe no catálogo"
        assert i18n.tr("Saúde do veículo: {text}", text="Bom") == "Vehicle health: Bom"   # valor chamado "text"
        assert i18n.tr_data("{não é um modelo}") == "{não é um modelo}"
    finally:
        i18n.set_language("pt")
    assert i18n.set_language("xx") == "pt"            # idioma desconhecido: português


def test_switching_to_english_changes_what_the_user_sees():
    from rad import connstate, fault_advice, journal, report, vag_data
    from rad.obd import dtc, pids
    i18n.set_language("en")
    try:
        assert vag_data.module_name(0x01) == "Engine electronics"
        f = vag_data.decode_fault(532, 0x87)                    # 00532 tensão de alimentação, intermitente
        assert f["desc"] and f["desc"] == EN.get(vag_data.VAG_DTC[532], f["desc"])
        adv = fault_advice.advice(f, 0x01)
        assert adv["severity_text"].endswith("severity") and adv["severity_short"] in ("High", "Medium", "Low")
        assert all(c in EN.values() for c in adv["causes"])
        assert connstate.LinkStatus(connstate.NO_DEVICE).message == "No interface"
        assert pids.name(0x0C) == "Engine speed" and pids.TABLE[0x51].decode(bytes([4])) == "Diesel"
        assert dtc.describe("P0101")["desc"] == "Air mass meter — range/performance"
        assert vag_data.decode_value(4, 10, 150)["unit"] == "° BTDC"
        change = {"kind": "coding", "channel": None, "before": 2, "after": 4102, "requested": 4102, "status": "ok"}
        assert journal.describe(change) == "Coding: 00002 → 04102"
        items = [{"address": 1, "module": vag_data.module_name(1), "status": "ok",
                  "info": {"part": "038906019FN", "component": "1,9l", "coding": 2}, "faults": [f]}]
        html = report.build_html({"name": "Garage"}, {"plate": "AA-00-00"}, items, meta={"changes": [change]})
        for text in ("Vehicle health", "Customer", "Interventions on the modules", "Generated by", "lang=\"en\""):
            assert text in html, text
        assert "Saúde do veículo" not in html and "Relatório de diagnóstico" not in html
    finally:
        i18n.set_language("pt")
    assert vag_data.module_name(0x01) == "Electrónica do motor"


